void fb_init(uint64_t mb2_info) {
    extern void printk(const char *fmt, ...);
    fb.addr = 0;
    fb.width = 1024;
    fb.height = 768;
    fb.pitch = 4096;
    fb.bpp = 32;
    fb.backbuf = 0;

    if (!mb2_info) { printk("fb: no mb2_info\n"); return; }

    uint32_t total_size = *(uint32_t*)mb2_info;
    printk("fb: mb2_info at 0x%x, total_size=%d\n", mb2_info, total_size);

    struct {
        uint32_t type;
        uint32_t size;
    } __attribute__((packed)) *tag = (void*)(mb2_info + 8);

    while (tag->type != 0 && (uint64_t)tag < mb2_info + total_size) {
        printk("fb: tag type=%d size=%d\n", tag->type, tag->size);
        if (tag->type == 8) {
            struct {
                uint32_t type;
                uint32_t size;
                uint64_t addr;
                uint32_t pitch;
                uint32_t width;
                uint32_t height;
                uint8_t bpp;
                uint8_t fb_type;
            } __attribute__((packed)) *fb_tag = (void*)tag;

            fb.addr = fb_tag->addr;
            fb.pitch = fb_tag->pitch;
            fb.width = fb_tag->width;
            fb.height = fb_tag->height;
            fb.bpp = fb_tag->bpp;

            printk("fb: found! addr=0x%x pitch=%d %dx%d@%d type=%d\n",
                   fb.addr, fb.pitch, fb.width, fb.height, fb.bpp, fb_tag->fb_type);

            if (fb.addr != 0) {
                uint64_t fb_phys = fb.addr;
                uint64_t fb_size = (uint64_t)fb.pitch * fb.height;
                for (uint64_t off = 0; off < fb_size; off += 0x200000) {
                    paging_map_2mb(fb_phys + off, fb_phys + off);
                }

                uint32_t pages_needed = (uint32_t)((fb_size + 4095) / 4096);
                uint8_t *buf = 0;
                for (uint32_t i = 0; i < pages_needed; i++) {
                    uint8_t *page = (uint8_t *)page_alloc();
                    if (!page) break;
                    if (i == 0) buf = page;
                }
                if (buf) {
                    fb.backbuf = buf;
                    for (uint64_t off = 0; off < (uint64_t)pages_needed * 4096; off += 0x200000) {
                        paging_map_2mb((uint64_t)buf + off, (uint64_t)buf + off);
                    }
                }
            }
            break;
        }
        tag = (void*)((uint64_t)tag + ((tag->size + 7) & ~7));
    }
}

uint32_t fb_color(uint8_t r, uint8_t g, uint8_t b) {
    return (r << 16) | (g << 8) | b;
}

uint32_t fb_blend(uint32_t c1, uint32_t c2, uint8_t alpha) {
    uint8_t r1 = (c1 >> 16) & 0xFF, g1 = (c1 >> 8) & 0xFF, b1 = c1 & 0xFF;
    uint8_t r2 = (c2 >> 16) & 0xFF, g2 = (c2 >> 8) & 0xFF, b2 = c2 & 0xFF;
    uint8_t r = r1 + ((int32_t)(r2 - r1) * alpha >> 8);
    uint8_t g = g1 + ((int32_t)(g2 - g1) * alpha >> 8);
    uint8_t b = b1 + ((int32_t)(b2 - b1) * alpha >> 8);
    return (r << 16) | (g << 8) | b;
}

uint32_t fb_darken(uint32_t color, uint8_t amount) {
    uint8_t r = (color >> 16) & 0xFF;
    uint8_t g = (color >> 8) & 0xFF;
    uint8_t b = color & 0xFF;
    r = (r > amount) ? r - amount : 0;
    g = (g > amount) ? g - amount : 0;
    b = (b > amount) ? b - amount : 0;
    return (r << 16) | (g << 8) | b;
}

uint32_t fb_lighten(uint32_t color, uint8_t amount) {
    uint8_t r = (color >> 16) & 0xFF;
    uint8_t g = (color >> 8) & 0xFF;
    uint8_t b = color & 0xFF;
    r = (r + amount > 255) ? 255 : r + amount;
    g = (g + amount > 255) ? 255 : g + amount;
    b = (b + amount > 255) ? 255 : b + amount;
    return (r << 16) | (g << 8) | b;
}

void fb_putpixel(int32_t x, int32_t y, uint32_t color) {
    if (x < 0 || y < 0 || x >= (int32_t)fb.width || y >= (int32_t)fb.height) return;
    if (fb.backbuf) {
        uint32_t *pixel = (uint32_t*)(fb.backbuf + y * fb.pitch + x * 4);
        *pixel = color;
    } else {
        uint32_t *pixel = (uint32_t*)(fb.addr + y * fb.pitch + x * 4);
        *pixel = color;
    }
}

void fb_putpixel_back(int32_t x, int32_t y, uint32_t color) {
    if (x < 0 || y < 0 || x >= (int32_t)fb.width || y >= (int32_t)fb.height) return;
    if (!fb.backbuf) return;
    uint32_t *pixel = (uint32_t*)(fb.backbuf + y * fb.pitch + x * 4);
    *pixel = color;
}

uint32_t fb_getpixel(int32_t x, int32_t y) {
    if (x < 0 || y < 0 || x >= (int32_t)fb.width || y >= (int32_t)fb.height) return 0;
    if (fb.backbuf) {
        return *(uint32_t*)(fb.backbuf + y * fb.pitch + x * 4);
    }
    return *(uint32_t*)(fb.addr + y * fb.pitch + x * 4);
}

void fb_hline(int32_t x, int32_t y, int32_t w, uint32_t color) {
    for (int32_t i = 0; i < w; i++) fb_putpixel(x + i, y, color);
}

void fb_vline(int32_t x, int32_t y, int32_t h, uint32_t color) {
    for (int32_t i = 0; i < h; i++) fb_putpixel(x, y + i, color);
}

void fb_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color) {
    for (int32_t dy = 0; dy < h; dy++) {
        for (int32_t dx = 0; dx < w; dx++) {
            fb_putpixel(x + dx, y + dy, color);
        }
    }
}

void fb_rect_outline(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color, int32_t t) {
    fb_rect(x, y, w, t, color);
    fb_rect(x, y + h - t, w, t, color);
    fb_rect(x, y, t, h, color);
    fb_rect(x + w - t, y, t, h, color);
}

void fb_rect_rounded(int32_t x, int32_t y, int32_t w, int32_t h, int32_t r, uint32_t color) {
    for (int32_t dy = 0; dy < h; dy++) {
        for (int32_t dx = 0; dx < w; dx++) {
            int32_t px = x + dx, py = y + dy;
            int32_t draw = 1;
            if (dx < r && dy < r) {
                int32_t cx = r - dx, cy = r - dy;
                if (cx * cx + cy * cy > r * r) draw = 0;
            } else if (dx >= w - r && dy < r) {
                int32_t cx = dx - (w - r - 1), cy = r - dy;
                if (cx * cx + cy * cy > r * r) draw = 0;
            } else if (dx < r && dy >= h - r) {
                int32_t cx = r - dx, cy = dy - (h - r - 1);
                if (cx * cx + cy * cy > r * r) draw = 0;
            } else if (dx >= w - r && dy >= h - r) {
                int32_t cx = dx - (w - r - 1), cy = dy - (h - r - 1);
                if (cx * cx + cy * cy > r * r) draw = 0;
            }
            if (draw) fb_putpixel(px, py, color);
        }
    }
}

void fb_rect_gradient_v(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t c_top, uint32_t c_bot) {
    for (int32_t dy = 0; dy < h; dy++) {
        uint8_t alpha = (uint8_t)((int32_t)dy * 256 / h);
        uint32_t c = fb_blend(c_top, c_bot, alpha);
        fb_hline(x, y + dy, w, c);
    }
}

void fb_rect_gradient_h(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t c_left, uint32_t c_right) {
    for (int32_t dx = 0; dx < w; dx++) {
        uint8_t alpha = (uint8_t)((int32_t)dx * 256 / w);
        uint32_t c = fb_blend(c_left, c_right, alpha);
        fb_vline(x + dx, y, h, c);
    }
}

void fb_shadow(int32_t x, int32_t y, int32_t w, int32_t h, int32_t r, int32_t spread) {
    (void)r;
    for (int32_t dy = -spread; dy < h + spread; dy++) {
        for (int32_t dx = -spread; dx < w + spread; dx++) {
            int32_t px = x + dx, py = y + dy;
            if (dx >= 0 && dx < w && dy >= 0 && dy < h) continue;
            int32_t dist = 0;
            if (dx < 0) dist = -dx;
            else if (dx >= w) dist = dx - w + 1;
            if (dy < 0) { int32_t d = -dy; if (d > dist) dist = d; }
            else if (dy >= h) { int32_t d = dy - h + 1; if (d > dist) dist = d; }
            if (dist <= spread) {
                uint8_t alpha = (uint8_t)(20 * (spread - dist) / spread);
                uint32_t bg = fb_getpixel(px, py);
                uint32_t shadow = fb_color(0, 0, 0);
                uint32_t blended = fb_blend(bg, shadow, alpha);
                fb_putpixel(px, py, blended);
            }
        }
    }
}

void fb_fill(uint32_t color) {
    uint32_t *ptr = (uint32_t *)(fb.backbuf ? (uint64_t)fb.backbuf : fb.addr);
    for (uint32_t i = 0; i < fb.width * fb.height; i++) {
        ptr[i] = color;
    }
}

void fb_copy_back(void) {
    if (!fb.backbuf) return;
    uint8_t *dst = (uint8_t *)fb.addr;
    uint8_t *src = fb.backbuf;
    uint32_t row_bytes = fb.pitch;
    for (uint32_t y = 0; y < fb.height; y++) {
        __builtin_memcpy(dst + y * row_bytes, src + y * row_bytes, fb.width * 4);
    }
}

void fb_copy_region(int32_t x, int32_t y, int32_t w, int32_t h) {
    if (!fb.backbuf) return;
    for (int32_t dy = 0; dy < h; dy++) {
        for (int32_t dx = 0; dx < w; dx++) {
            int32_t px = x + dx, py = y + dy;
            if (px < 0 || py < 0 || px >= (int32_t)fb.width || py >= (int32_t)fb.height) continue;
            uint32_t pixel = *(uint32_t*)(fb.backbuf + py * fb.pitch + px * 4);
            fb_putpixel(px, py, pixel);
        }
    }
}

void fb_draw_char(int32_t x, int32_t y, char c, uint32_t color) {
    unsigned char uc = (unsigned char)c;
    if (uc > 127) uc = '?';
    const uint8_t *glyph = font_8x8[uc];
    for (int row = 0; row < 8; row++) {
        uint8_t row_data = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (row_data & (1 << (7 - col))) {
                fb_putpixel(x + col, y + row, color);
            }
        }
    }
}

void fb_draw_string(int32_t x, int32_t y, const char *s, uint32_t color) {
    int32_t cx = x;
    while (*s) {
        if (*s == '\n') {
            cx = x;
            y += 10;
        } else {
            fb_draw_char(cx, y, *s, color);
            cx += 8;
        }
        s++;
    }
}

void fb_draw_string_scaled(int32_t x, int32_t y, const char *s, uint32_t color, int32_t scale) {
    int32_t cx = x;
    while (*s) {
        if (*s == '\n') {
            cx = x;
            y += 8 * scale;
        } else {
            {
                unsigned char sc = (unsigned char)*s;
                const uint8_t *glyph = font_8x8[sc];
                for (int row = 0; row < 8; row++) {
                    for (int col = 0; col < 8; col++) {
                        if (glyph[row] & (1 << (7 - col))) {
                            for (int sy = 0; sy < scale; sy++) {
                                for (int sx = 0; sx < scale; sx++) {
                                    fb_putpixel(cx + col * scale + sx, y + row * scale + sy, color);
                                }
                            }
                        }
                    }
                }
            }
            cx += 8 * scale;
        }
        s++;
    }
}

int32_t fb_string_width(const char *s) {
    int32_t max_w = 0, cur_w = 0;
    while (*s) {
        if (*s == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else {
            cur_w += 8;
        }
        s++;
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}

int32_t fb_string_width_scaled(const char *s, int32_t scale) {
    return fb_string_width(s) * scale;
}
